#!/usr/bin/env python3
"""Build email digit masks from the storefront's IZLOM Heavy font (requires Pillow)."""
import base64
from pathlib import Path
import zlib
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
font = ImageFont.truetype(str(ROOT / 'frontend/public/fonts/IZLOM_Narrow-Heavy.ttf'), 240)
width, height = 128, 196
raw = bytearray()
for digit in '0123456789':
    image = Image.new('L', (width, height), 255)
    ImageDraw.Draw(image).text((0, -19), digit, font=font, fill=0)
    raw.extend(image.tobytes())
encoded = base64.b64encode(zlib.compress(bytes(raw), 9)).decode()
output = ROOT / 'backend/src/auth/email/digit-masks.ts'
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text('// Generated by scripts/build-email-digits.py from IZLOM_Narrow-Heavy.ttf.\n'
                  f'export const GLYPH_WIDTH = {width};\nexport const GLYPH_HEIGHT = {height};\n'
                  f'export const DIGIT_MASKS = "{encoded}";\n')
