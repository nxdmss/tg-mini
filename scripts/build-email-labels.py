"""Generate embedded email label glyphs from the storefront's IBM Plex Mono."""
from pathlib import Path
from io import BytesIO
import base64, zlib
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont
root = Path(__file__).resolve().parents[1]
chars = '0123456789: МИНУТДОСК'
fonts = {}
for subset in ('latin', 'cyrillic'):
    font = TTFont(root / f'frontend/node_modules/@fontsource/ibm-plex-mono/files/ibm-plex-mono-{subset}-700-normal.woff')
    font.flavor = None
    buffer = BytesIO()
    font.save(buffer)
    buffer.seek(0)
    fonts[subset] = ImageFont.truetype(buffer, 36)
raw = b''
for char in chars:
    img = Image.new('L', (28, 48), 255)
    ImageDraw.Draw(img).text((2, 0), char, font=fonts['cyrillic' if ord(char)>127 else 'latin'], fill=0)
    raw += img.tobytes()
(root/'backend/src/auth/email/label-masks.ts').write_text('// Generated by scripts/build-email-labels.py.\nexport const LABEL_CHARS = '+repr(chars)+';\nexport const LABEL_MASKS = "'+base64.b64encode(zlib.compress(raw)).decode()+'";\n')
